// Функции для работы с номером телефона.
// Внутри приложения номер хранится как строка из одних цифр: '79991234567'.

/**
 * Приводит введённый номер к виду из одних цифр с кодом страны.
 * '+7 (999) 123-45-67' → '79991234567'
 * Российский номер, набранный через 8, переводится в формат с 7: '89991234567' → '79991234567'.
 * Российский мобильный без кода страны получает 7: '9991234567' → '79991234567'.
 */
export function normalizePhone(input: string): string {
	// \D — любой символ, кроме цифры: убираем пробелы, скобки, дефисы, «+»
	const digits = input.replace(/\D/g, '');
	if (digits.length === 11 && digits.startsWith('8')) {
		return `7${digits.slice(1)}`;
	}
	// 10 цифр, начинается с 9 — мобильный номер России без кода страны.
	// Без кода GREEN-API не отправит сообщение, а ответ придёт с номером 7... и попадёт в другой чат
	if (digits.length === 10 && digits.startsWith('9')) {
		return `7${digits}`;
	}
	return digits;
}

/**
 * Проверяет уже нормализованный номер: от 11 до 15 цифр.
 * 11 — минимум для номера с кодом страны в странах, где работает MAX (Россия: 7 + 10 цифр);
 * более короткий номер почти наверняка введён без кода. 15 — максимум по стандарту E.164.
 */
export function isValidPhone(phone: string): boolean {
	return /^\d{11,15}$/.test(phone);
}

/**
 * Адрес чата для sendMessage: '79991234567' → '79991234567@c.us'.
 */
export function toChatId(phone: string): string {
	return `${phone}@c.us`;
}
